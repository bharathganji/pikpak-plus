-- Tordroid Plus: complete, locked-down Supabase schema
--
-- Run once in Supabase Dashboard -> SQL Editor -> New query -> Run.
--
-- Unlike supabase_schema.sql + migration_add_users.sql, this grants NO access
-- to the public (anon / publishable) key. RLS is enabled with no policies, so
-- only the server's SECRET key (sb_secret_..., which bypasses RLS) can read or
-- write. Put that secret key in SUPABASE_KEY on the server.
-- Safe to re-run.

-- public_actions: log of tasks/shares created by users
create table if not exists public_actions (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    action text not null,
    data jsonb default '{}'::jsonb,
    user_email text
);

-- daily_statistics: daily aggregated usage
create table if not exists daily_statistics (
    id bigint generated by default as identity primary key,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    date date not null unique,
    tasks_added integer default 0,
    storage_used bigint default 0,
    transfer_used bigint default 0,
    downstream_traffic bigint default 0,
    premium_expiration timestamp with time zone
);

-- pikpak_tokens: singleton row holding the PikPak login session
create table if not exists pikpak_tokens (
    id integer primary key default 1,
    username text,
    password text,
    access_token text,
    refresh_token text,
    access_token_expires_at timestamp with time zone,
    refresh_token_expires_at timestamp with time zone,
    user_id text,
    captcha_token text,
    captcha_expires_at timestamp with time zone,
    updated_at timestamp with time zone default now(),
    constraint single_row check (id = 1)
);

-- users: family accounts
create table if not exists users (
    id bigint generated by default as identity primary key,
    email text unique not null,
    password_hash text not null,
    is_admin boolean default false,
    blocked boolean default false,
    reset_token text,
    reset_token_expires_at timestamp with time zone,
    created_at timestamp with time zone default timezone('utc'::text, now()) not null,
    updated_at timestamp with time zone default timezone('utc'::text, now()) not null
);

-- Indexes
create index if not exists idx_daily_statistics_date on daily_statistics(date desc);
create index if not exists idx_public_actions_created_at on public_actions(created_at desc);
create index if not exists idx_public_actions_action_created on public_actions(action, created_at desc);
create index if not exists idx_public_actions_magnet_hash on public_actions((data->>'info_hash')) where action = 'add';
create index if not exists idx_public_actions_url on public_actions((data->>'url')) where action = 'add';
create index if not exists idx_public_actions_file_id on public_actions((data->>'file_id')) where action = 'share';
create index if not exists idx_public_actions_user_email on public_actions(user_email);
create index if not exists idx_users_email on users(email);
create index if not exists idx_users_blocked on users(blocked);
create index if not exists idx_users_is_admin on users(is_admin);
create index if not exists idx_users_reset_token on users(reset_token) where reset_token is not null;

-- updated_at trigger for users
create or replace function update_updated_at_column()
returns trigger as $$
begin
    new.updated_at = timezone('utc'::text, now());
    return new;
end;
$$ language plpgsql set search_path = '';

drop trigger if exists update_users_updated_at on users;
create trigger update_users_updated_at before update on users
    for each row execute function update_updated_at_column();

-- Lock down: RLS on, remove every policy (including any from the upstream
-- scripts), and revoke table grants from the public roles.
do $$
declare
    t text;
    p record;
begin
    foreach t in array array['public_actions', 'daily_statistics', 'pikpak_tokens', 'users'] loop
        execute format('alter table public.%I enable row level security', t);
        for p in select policyname from pg_policies where schemaname = 'public' and tablename = t loop
            execute format('drop policy %I on public.%I', p.policyname, t);
        end loop;
        execute format('revoke all on public.%I from anon, authenticated', t);
    end loop;
end $$;
